# Selection Sort
def selectionSort(arr):
    for i in range(0, len(arr) - 1):
        jMin = i
        for j in range(i + 1, len(arr)):
            if arr[j] < arr[jMin]:
                jMin = j
        if jMin != i:
            arr[i], arr[jMin] = arr[jMin], arr[i]
    return arr

